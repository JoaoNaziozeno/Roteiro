    phases = copy.deepcopy(BASE_MAT_PHASES)
    for p in phases:
        for grp in p['g']:
            for t in grp[1]:
                title = t.get('title')
                if title in ALL_GUIDES:
                    t['pt_guide'] = ALL_GUIDES[title]
    return phases
